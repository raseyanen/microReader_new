static uint16_t texGlyph3(char ch) {
  if (ch >= 'a' && ch <= 'z') ch -= 32;
  if (ch >= 32 && ch <= 95) return texFont3x5[ch - 32];
  switch (ch) {
    case '{': return TG3(3,2,6,2,3);
    case '|': return TG3(2,2,2,2,2);
    case '}': return TG3(6,2,3,2,6);
    case '~': return TG3(0,3,6,0,0);
  }
  return texFont3x5['?' - 32];
}

